#!/usr/bin/env python3
"""Full-Stack Off-Screen Minecraft Server + Headless Bot Fleet Docker Compose Generator."""

from __future__ import annotations

from typing import Any


def generate_full_docker_stack(
    *,
    server_type: str = "PAPER",
    mc_version: str = "1.21.4",
    server_memory: str = "2G",
    concurrent_bots: int = 8,
    include_velocity: bool = False,
    include_visual_bot: bool = True,
) -> dict[str, Any]:
    stype = (server_type or "PAPER").strip().upper()
    if stype not in ("PAPER", "FOLIA", "PURPUR"):
        stype = "PAPER"
    bots = max(1, min(int(concurrent_bots), 25))
    bot_pool_mem_mb = max(256, bots * 42 + 128)

    lines = [
        "# Generated by MinecraftKit — Anti-OOM Full-Stack Headless Minecraft QA Grid",
        "# Zero desktop Minecraft tabs · Zero screen/focus hijacking · Safe for laptops & VPS",
        "services:",
        "  mc-server:",
        "    image: itzg/minecraft-server:java21",
        "    restart: unless-stopped",
        "    environment:",
        '      EULA: "TRUE"',
        f'      TYPE: "{stype}"',
        f'      VERSION: "{mc_version}"',
        f'      MEMORY: "{server_memory}"',
        '      ONLINE_MODE: "FALSE"',
        '      USE_AIKAR_FLAGS: "TRUE"',
        "    ports:",
        '      - "127.0.0.1:25565:25565"',
        '      - "127.0.0.1:25590:25590"',
        "    volumes:",
        "      - ./plugins:/plugins:ro",
        "      - mc-data:/data",
        "    healthcheck:",
        '      test: ["CMD", "mc-health"]',
        "      interval: 10s",
        "      timeout: 5s",
        "      retries: 18",
    ]

    if include_velocity:
        lines.extend([
            "",
            "  velocity-proxy:",
            "    image: itzg/mc-proxy:java21",
            "    environment:",
            '      TYPE: "VELOCITY"',
            '      MEMORY: "512M"',
            "    ports:",
            '      - "25577:25577"',
            "    depends_on:",
            "      mc-server:",
            "        condition: service_healthy",
        ])

    lines.extend([
        "",
        "  mckit-protocol-bots:",
        "    build:",
        "      context: .",
        "      dockerfile: docker/Dockerfile.protocol-bot",
        f"    mem_limit: {bot_pool_mem_mb}m",
        "    environment:",
        '      MCKIT_HOST: "mc-server"',
        '      MCKIT_PORT: "25565"',
        f'      MCKIT_BOT_COUNT: "{bots}"',
        '      MCKIT_BOT_PASS: "${MCKIT_BOT_PASS:-MckitStagePass123!}"',
        "    depends_on:",
        "      mc-server:",
        "        condition: service_healthy",
    ])

    if include_visual_bot:
        lines.extend([
            "",
            "  mckit-visual-bot:",
            "    profiles: [visual]",
            "    build:",
            "      context: .",
            "      dockerfile: docker/Dockerfile.visual-bot",
            "    mem_limit: 1600m",
            "    environment:",
            '      DISPLAY: ":99"',
            '      MCKIT_HOST: "mc-server"',
            '      MCKIT_PORT: "25565"',
            "    volumes:",
            "      - ./qa-captures:/captures",
            "    depends_on:",
            "      mc-server:",
            "        condition: service_healthy",
        ])

    lines.extend([
        "",
        "volumes:",
        "  mc-data:",
    ])

    yaml_text = "\n".join(lines) + "\n"
    return {
        "ok": True,
        "filename": "docker-compose.mckit-full.yml",
        "server_type": stype,
        "mc_version": mc_version,
        "concurrent_bots": bots,
        "bot_pool_mem_limit_mb": bot_pool_mem_mb,
        "visual_bot_mem_limit_mb": 1600 if include_visual_bot else 0,
        "screen_lock_free": True,
        "yaml": yaml_text,
    }
